  # A torus is the plane modulo a lattice, here ℤ + τℤ. The "Torus" viewer
  # says so in its header (`modulo the lattice τ`): each pixel's point is
  # folded into the lattice's parallelogram before the code sees it, so the
  # picture repeats over the plane, and `side_distance` is how far the
  # folded point is from the parallelogram's sides. Its menu's "Show
  # fundamental domain" shows just one cell.
  #
  # It's colored by the Weierstrass ℘ function of the lattice, which is
  # periodic in it: a double pole at the lattice's points, and two zeros
  # in each cell. (Type ℘ as \wp in the editor.)
  #
  # Which τ gives which torus? τ and (aτ + b)/(cτ + d), for integers with
  # ad - bc = 1, give the same lattice, so the same torus; the "Shapes"
  # viewer is the upper half-plane modulo the modular group, which folds
  # every τ to the one that represents its torus, colored by Klein's
  # j-invariant, which tells the tori apart (its argument as a hue, and
  # bands of |j|, which grows very fast up the half-plane). Click it to
  # pick τ (its Select
  # tool), or let the "Sweep" tool's timer move τ around.

  @config "Lattice"
  τ : C as "τ =" := 0.3 + 1.1 i
  edges : Boolean as "Draw the tiles' edges" := true

  @viewer "Torus" modulo the lattice τ
  setup:
    pixel size: 1/120
  color <- if edges and side_distance < pixel_size then white else domain_color(℘(z, 1, τ) / 10)

  @viewer "Shapes" over τ on the half-plane modulo the modular group
  setup:
    pixel size: 1/150
  j := klein_j(τ)
  hue := rainbow(arg j / (2 π))
  color <- if side_distance < 1.5 pixel_size / im(τ) then white else blend(cos(log |j| / 2)^2, dark hue, light hue)

  # τ, marked in each tile of the shapes
  @tool overlay for "Shapes"
  on refresh:
    erase
    use white for stroke
    draw circle at τ with radius 5 pixels

  @tool "Mark" for "Torus" with shortcut m
  text "Click the torus to see ℘ and ℘' there. (The mark is in every tile: they're all the same point of the torus.)"
  value : C as "℘ =" := 0
  slope : C as "℘' =" := 0
  on click:
    p := click
    erase
    use white for stroke
    use white for fill
    draw filled circle at p with radius 4 pixels
    value <- ℘(p, 1, τ)
    slope <- ℘'(p, 1, τ)
  on deactivated:
    erase

  @tool "Sweep" for "Torus" with shortcut s
  text "While this tool is selected, τ goes around a circle, and the torus changes shape."
  speed : R as "Turns per minute" := 6
  angle : R := 0
  on timer "turn" every 50 ms:
    angle <- angle + speed 2π / 1200
    τ <- 0.25 + 1.1 i + 0.3 e^(i angle)
