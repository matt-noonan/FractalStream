  r : ℝ as "Radius for residue integral: " ≔ 0.1
  steps : ℤ as "Integration steps: " ≔ 1000
  z0 : ℂ ≔ 1

  @common
  f(z) ≔ 1 / (z² - 1)²

  @viewer "z plane"
  w ≔ f(z)
  color ⟵ hsl(1/2 + ((arg(w) + 3 π / 2)/ (2 π)), 1, 2 arctan(|w|) / π)

  @tool overlay for="z plane"
  on refresh:
    erase
    res ≔ residue(f, z0, r, steps)
    use white for line
    write text("Res_{", z0, "}(f) = ", res) at i
    draw point at z0
    draw circle at z0 with radius r
    
