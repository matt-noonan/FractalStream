script: |
  @config "Parameter value"
  C : ℂ ≔ 0
  draw_lines : Boolean as "Connect orbit points with lines" ≔ true

  @common
  f(z) ≔ z² + C

  @viewer "Parameter plane" var=C
  z ≔ 0
  iterate z ⟼ f(z) until z escapes

  @viewer "Dynamics"
  iterate z ⟼ f(z) until z escapes

  @tool overlay for="Dynamics"
  on refresh:
    erase
    found, z, period ≔ find_cycle(f, 0, 10000, 100, (x,y) ⟼ x = y, x ⟼ |x| < 2)
    if found:
      repeat period times:
        draw point at z
        z ⟵ f(z)
        if draw_lines:
          draw line from z to previous z    
      write text("Period ", period) at 1.5 i
    else:
      write "Could not find the attracting cycle" at 1.5 i
