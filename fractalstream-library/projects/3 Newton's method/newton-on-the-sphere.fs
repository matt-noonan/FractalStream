script: |
  @common
  f(z) := z^3 - 2 z + 2
  # one step of Newton's method
  newton(z) := z - f(z) / f'(z)

  @viewer "Newton's method on the sphere" over z on the sphere
  setup:
    center: -1.5
  iterate z -> newton(z) until z stops
  if stuck:
    color <- black
  else:
    if re(affine(1, z)) < 0:
      color ⟵ yellow
    else if im(affine(1, z)) > 0:
      color ⟵ purple
    else:
      color ⟵ green
    color <- cycle(iterations / 20, light color, dark color)

  @tool "Trace" for "Newton's method on the sphere" with shortcut t
  on deactivated:
    erase
  on click:
    z := click
    erase
    repeat up to 60 times:
      z <- newton(z)
      draw point at previous z
      draw line from previous z to z
    until z stops
    draw point at z
