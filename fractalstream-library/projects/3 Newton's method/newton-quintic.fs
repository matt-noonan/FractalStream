script: |
  @common
  # z⁵ - z - 1 is the classic polynomial whose roots can't be written down
  # with radicals: there's no formula for them, so they can't be listed
  # here, ready to color by. Instead, the viewer's Autocolor colorizer
  # gives each root a color of its own the first time Newton's method
  # finds it.
  let f(z) = z^5 - z - 1
  # one step of Newton's method
  let newton(z) = z - f(z) / f'(z)

  @viewer "Roots of f" colorizer=Autocolor center=0 pixelSize=1/150
  lastZ := 0
  repeat:
    lastZ <- z
    z <- newton(z)
  until z = lastZ

  @tool "Trace" for="Roots of f" shortcut=t
  on deactivated:
    erase
  on click-or-drag:
    lastZ := 0
    erase
    use white for stroke
    repeat:
      lastZ <- z
      z <- newton(z)
      draw point at lastZ
      draw line from lastZ to z
    until z = lastZ
    draw point at z
