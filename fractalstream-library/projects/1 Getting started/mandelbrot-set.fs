script: |
  @viewer "Mandelbrot set with smooth coloring" var=C
  z ≔ 0
  iterate z ⟼ z² + C until z escapes

  if z escaped:
    # see https://linas.org/art-gallery/escape/ray.html
    m ≔ iterations + 1 - log (log (|z|²) / (2 log escape_radius)) / log 2
    color ⭠ blend (2 arctan (m / 20) / pi, red, white)
  else:
    color ⭠ black
