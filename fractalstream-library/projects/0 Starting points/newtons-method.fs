script: |
  @common
  # find the roots of f with Newton's method
  let f(z) = z^3 - 1
  # one step of Newton's method
  let newton(z) = z - f(z) / f'(z)
  # colors for the basins of attraction, and for failure to converge;
  # these can use color names like `red` or `black`, or color functions
  # involving `z` and `iterations`
  let basin_color(z) = rainbow(arg z / (2π))
  let on_failure(z) = black

  @config "Configuration"
  shade_convergence : Boolean as "Shade by convergence speed: " <- true

  @viewer "Newton's method on ℂ"
  lastZ := 0
  repeat:
    lastZ <- z
    z <- newton(z)
  until z = lastZ

  if stuck:
    color <- on_failure(z)
  else:
    color <- basin_color(z)
    if shade_convergence:
      color <- blend(iterations / 20, dark color, light color)

  @tool "Trace" shortcut=t
  on refresh:
    erase
  on deactivated:
    erase
  on click-or-drag:
    use white for line
    erase
    prevZ := z
    repeat:
      prevZ <- z
      draw point at z
      z <- newton(z)
      draw line from z to prevZ
    until z = prevZ
