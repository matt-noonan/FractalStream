  define script:
    iterate z -> z^2 + i until z escapes
    if stuck:
      color <- black
    else if im z > 0:
      color <- light rainbow(iterations / 20)
    else:
      color <- dark rainbow(iterations / 20)

  @viewer "One-variable complex dynamics" pixelSize=1/100
  run script
